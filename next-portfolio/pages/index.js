const SITE_URL = 'https://anirbanbhk88.github.io'
const SITE_TITLE = 'Anirban Bhowmick — AI Engineer'
const SITE_DESCRIPTION =
    'AI Engineer with 8+ years bridging research (Fraunhofer IAIS) and enterprise software (TCS), specializing in RAG systems, LLM fine-tuning and scalable AI deployment. Based in Sankt Augustin (near Bonn), Germany.'

/**
 * Reads the latest posts from the blog manifest (data/posts.json, generated by
 * scripts/build-posts.js). A missing or empty manifest must NEVER break the
 * build — hence the try/catch with an empty-array fallback.
 */
function readLatestPosts(count = 3) {
    try {
        const manifestPath = path.join(process.cwd(), 'data', 'posts.json')
        const raw = fs.readFileSync(manifestPath, 'utf8')
        const manifest = JSON.parse(raw)
        return Array.isArray(manifest.posts) ? manifest.posts.slice(0, count) : []
    } catch (err) {
        return []
    }
}

export async function getStaticProps() {
    return {
        props: {
            posts: readLatestPosts(3),
        },
    }
}

